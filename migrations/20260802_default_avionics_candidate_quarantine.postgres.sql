-- This is the shared catalog-mutation lock order. It makes product approval,
-- the canonical snapshot, and pending insertion one linearized operation.
LOCK TABLE avionics_models, aircraft_model_variant_default_avionics,
  aircraft_model_variant_default_avionics_candidates
  IN SHARE ROW EXCLUSIVE MODE;

-- Version 1 could copy an unapproved canonical row, then observe a concurrent
-- product approval during deletion. Repair only that exact race signature:
-- the approved canonical row and its legacy-provenance candidate must match
-- byte-for-byte. Any other overlap is corruption and fails the postcondition.
DELETE FROM aircraft_model_variant_default_avionics_candidates candidate
USING aircraft_model_variant_default_avionics active,
      avionics_models model
WHERE model.id = active.avionics_model_id
  AND model.catalog_status = 'approved'
  AND candidate.quarantined_default_avionics_id = active.id
  AND candidate.aircraft_model_variant_id = active.aircraft_model_variant_id
  AND candidate.model_year = active.model_year
  AND candidate.avionics_model_id = active.avionics_model_id
  AND candidate.quantity = active.quantity
  AND candidate.source_url = active.source_url
  AND candidate.source_title = active.source_title
  AND candidate.source_notes = active.source_notes
  AND candidate.source_confidence = active.source_confidence
  AND candidate.pending_reason = 'catalog_product_unverified'
  AND candidate.quarantined_created_at = active.created_at
  AND candidate.quarantined_updated_at = active.updated_at;

