CREATE OR REPLACE FUNCTION require_exact_pending_default_avionics_admission()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  -- Use the same semantic transaction lock as candidate insertion so
  -- concurrent canonical/candidate writes cannot both pass their checks.
  PERFORM pg_advisory_xact_lock(
    hashtextextended(
      concat_ws(
        ':',
        'aircraft_model_variant_default_avionics',
        NEW.aircraft_model_variant_id::text,
        NEW.model_year::text,
        NEW.avionics_model_id::text
      ),
      0
    )
  );

  IF EXISTS (
    SELECT 1
    FROM aircraft_model_variant_default_avionics_candidates candidate
    WHERE candidate.aircraft_model_variant_id = NEW.aircraft_model_variant_id
      AND candidate.model_year = NEW.model_year
      AND candidate.avionics_model_id = NEW.avionics_model_id
  ) AND NOT EXISTS (
    SELECT 1
    FROM aircraft_model_variant_default_avionics_candidates candidate
    WHERE candidate.aircraft_model_variant_id = NEW.aircraft_model_variant_id
      AND candidate.model_year = NEW.model_year
      AND candidate.avionics_model_id = NEW.avionics_model_id
      AND candidate.quantity = NEW.quantity
      AND candidate.source_url = NEW.source_url
      AND candidate.source_title = NEW.source_title
      AND candidate.source_notes = NEW.source_notes
      AND candidate.source_confidence = NEW.source_confidence
  ) THEN
    RAISE EXCEPTION
      'canonical default admission must exactly match its pending claim';
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS aircraft_default_avionics_candidate_admission_guard
