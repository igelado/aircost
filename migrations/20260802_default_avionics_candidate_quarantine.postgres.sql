CREATE OR REPLACE FUNCTION reject_active_default_avionics_candidate()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  -- Serialize both sides of the cross-table uniqueness check on the semantic
  -- claim key. PostgreSQL table-level locks acquired from opposite INSERT
  -- triggers can deadlock; this transaction-scoped advisory lock gives both
  -- paths the same lock without reducing concurrency between unrelated claims.
  PERFORM pg_advisory_xact_lock(
    hashtextextended(
      concat_ws(
        ':',
        'aircraft_model_variant_default_avionics',
        NEW.aircraft_model_variant_id::text,
        NEW.model_year::text,
        NEW.avionics_model_id::text
      ),
      0
    )
  );

  IF EXISTS (
    SELECT 1
    FROM aircraft_model_variant_default_avionics active
    WHERE active.aircraft_model_variant_id = NEW.aircraft_model_variant_id
      AND active.model_year = NEW.model_year
      AND active.avionics_model_id = NEW.avionics_model_id
  ) THEN
    RAISE EXCEPTION
      'default avionics claim already exists in the canonical table';
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS aircraft_default_avionics_candidate_active_conflict_insert
