CREATE TRIGGER aircraft_make_tcds_lineage_collision
BEFORE INSERT OR UPDATE OF name, normalized_name ON aircraft_makes
FOR EACH ROW EXECUTE FUNCTION prevent_aircraft_make_lineage_label_collision();

