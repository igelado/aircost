CREATE OR REPLACE FUNCTION aircraft_tcds_make_lineage_matches(
  wanted_snapshot_date TEXT,
  wanted_archive_sha256 TEXT,
  wanted_aircraft_code TEXT,
  wanted_make_id BIGINT,
  wanted_designation_id BIGINT,
  wanted_faa_make TEXT,
  wanted_faa_model TEXT,
  wanted_serial_key TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $function$
  SELECT count(*) = 1
  FROM aircraft_tcds_make_lineage_bindings binding
  WHERE binding.faa_snapshot_date = wanted_snapshot_date
    AND binding.faa_archive_sha256 = wanted_archive_sha256
    AND binding.faa_aircraft_code = wanted_aircraft_code
    AND binding.aircraft_make_id = wanted_make_id
    AND binding.aircraft_designation_id = wanted_designation_id
    AND binding.faa_manufacturer_name = wanted_faa_make
    AND binding.faa_model = wanted_faa_model
    AND length(wanted_serial_key) =
      length(binding.serial_prefix) + binding.serial_digits_width
    AND left(wanted_serial_key, length(binding.serial_prefix)) =
      binding.serial_prefix
    AND substring(
      wanted_serial_key FROM length(binding.serial_prefix) + 1
    ) ~ '^[0-9]+$'
    AND CAST(substring(
      wanted_serial_key FROM length(binding.serial_prefix) + 1
    ) AS BIGINT) >= binding.first_serial_number
    AND (
      binding.last_serial_number IS NULL
      OR CAST(substring(
        wanted_serial_key FROM length(binding.serial_prefix) + 1
      ) AS BIGINT) <= binding.last_serial_number
    );
$function$;

CREATE OR REPLACE FUNCTION prevent_aircraft_make_lineage_label_collision()
RETURNS TRIGGER AS $function$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM aircraft_tcds_make_lineage_bindings binding
    WHERE binding.aircraft_make_id <> coalesce(NEW.id, -1)
      AND translate(
        lower(trim(NEW.name)),
        ' -./_,&' || chr(39) || '()',
        ''
      ) = translate(
        lower(trim(binding.faa_manufacturer_name)),
        ' -./_,&' || chr(39) || '()',
        ''
      )
  ) THEN
    RAISE EXCEPTION
      'canonical aircraft make collides with an approved FAA/TCDS lineage label';
  END IF;
  RETURN NEW;
END;
$function$ LANGUAGE plpgsql;

