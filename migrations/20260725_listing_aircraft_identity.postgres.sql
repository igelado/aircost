CREATE OR REPLACE FUNCTION prevent_aircraft_make_alias_collision()
RETURNS TRIGGER AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM aircraft_make_aliases alias
    WHERE alias.aircraft_make_id <> COALESCE(NEW.id, -1)
      AND trim(regexp_replace(lower(NEW.name), '[^a-z0-9]+', ' ', 'g'))
        = alias.normalized_alias
  ) THEN
    RAISE EXCEPTION 'canonical aircraft make collides with an approved alias';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

