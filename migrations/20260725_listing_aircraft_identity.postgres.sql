  SELECT constraint_row.conname,
         pg_get_constraintdef(constraint_row.oid, true)
  INTO existing_constraint_name, existing_constraint_definition
  FROM pg_constraint constraint_row
  WHERE constraint_row.conrelid =
      'aircraft_sale_listing_identity_assignments'::regclass
    AND constraint_row.confrelid =
      'aircraft_sale_listing_identity_assignments'::regclass
    AND constraint_row.contype = 'f'
    AND (
      SELECT array_agg(attribute.attname::TEXT ORDER BY column_key.ordinality)
      FROM unnest(constraint_row.conkey)
        WITH ORDINALITY AS column_key(attnum, ordinality)
      JOIN pg_attribute attribute
        ON attribute.attrelid = constraint_row.conrelid
       AND attribute.attnum = column_key.attnum
    ) = ARRAY['supersedes_assignment_id', 'aircraft_sale_listing_id']
    AND (
      SELECT array_agg(attribute.attname::TEXT ORDER BY column_key.ordinality)
      FROM unnest(constraint_row.confkey)
        WITH ORDINALITY AS column_key(attnum, ordinality)
      JOIN pg_attribute attribute
        ON attribute.attrelid = constraint_row.confrelid
       AND attribute.attnum = column_key.attnum
    ) = ARRAY['id', 'aircraft_sale_listing_id']
  LIMIT 1;

