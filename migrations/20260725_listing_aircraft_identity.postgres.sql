      ADD CONSTRAINT aircraft_listing_identity_assignment_supersedes_fk
      FOREIGN KEY (supersedes_assignment_id, aircraft_sale_listing_id)
      REFERENCES aircraft_sale_listing_identity_assignments(
        id, aircraft_sale_listing_id
      )
      ON DELETE CASCADE;
  ELSIF existing_constraint_name <>
      'aircraft_listing_identity_assignment_supersedes_fk' THEN
    EXECUTE format(
      'ALTER TABLE aircraft_sale_listing_identity_assignments RENAME CONSTRAINT %I TO aircraft_listing_identity_assignment_supersedes_fk',
      existing_constraint_name
    );
  END IF;
