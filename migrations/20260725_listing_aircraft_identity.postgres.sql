    ALTER TABLE aircraft_sale_listing_identity_assignments
      ADD CONSTRAINT aircraft_listing_identity_assignment_supersedes_fk
      FOREIGN KEY (supersedes_assignment_id, aircraft_sale_listing_id)
      REFERENCES aircraft_sale_listing_identity_assignments(
        id, aircraft_sale_listing_id
      )
      ON DELETE CASCADE;
  ELSIF position(
      'ON DELETE CASCADE' IN upper(existing_constraint_definition)
    ) = 0 THEN
    EXECUTE format(
      'ALTER TABLE aircraft_sale_listing_identity_assignments DROP CONSTRAINT %I',
      existing_constraint_name
