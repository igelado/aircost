  ON aircraft_makes;
CREATE TRIGGER aircraft_make_identity_alias_collision
BEFORE INSERT OR UPDATE ON aircraft_makes
FOR EACH ROW EXECUTE FUNCTION prevent_aircraft_make_alias_collision();

