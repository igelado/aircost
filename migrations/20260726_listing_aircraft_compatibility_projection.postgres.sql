CREATE OR REPLACE FUNCTION prevent_projected_aircraft_evidence_variant_move()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF NEW.aircraft_model_variant_id IS DISTINCT FROM
     OLD.aircraft_model_variant_id
    AND (
      EXISTS (
        SELECT 1
        FROM aircraft_valuation_compatibility_projections projection
        WHERE projection.aircraft_model_variant_id =
            OLD.aircraft_model_variant_id
      )
      OR EXISTS (
        SELECT 1
        FROM aircraft_valuation_compatibility_projections projection
        WHERE projection.aircraft_model_variant_id =
            NEW.aircraft_model_variant_id
      )
    ) THEN
    IF TG_TABLE_NAME = 'aircraft_model_spec_versions' THEN
      RAISE EXCEPTION 'aircraft spec evidence cannot move into or out of a projected variant';
    ELSIF TG_TABLE_NAME = 'aircraft_model_variant_price_points' THEN
      RAISE EXCEPTION 'aircraft price evidence cannot move into or out of a projected variant';
    ELSE
      RAISE EXCEPTION 'default avionics evidence cannot move into or out of a projected variant';
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;

