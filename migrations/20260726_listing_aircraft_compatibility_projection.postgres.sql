      SELECT 1 FROM aircraft_sale_listings listing
      WHERE listing.id = OLD.aircraft_sale_listing_id
    )
    AND NEW.id IS NOT DISTINCT FROM OLD.id
    AND NEW.source_url IS NOT DISTINCT FROM OLD.source_url
    AND NEW.observed_make IS NOT DISTINCT FROM OLD.observed_make
    AND NEW.observed_family IS NOT DISTINCT FROM OLD.observed_family
    AND NEW.observed_designation IS NOT DISTINCT FROM OLD.observed_designation
    AND NEW.model_year IS NOT DISTINCT FROM OLD.model_year
    AND NEW.serial_number IS NOT DISTINCT FROM OLD.serial_number
    AND NEW.registration_number IS NOT DISTINCT FROM OLD.registration_number
    AND NEW.input_json IS NOT DISTINCT FROM OLD.input_json
    AND NEW.observation_sha256 IS NOT DISTINCT FROM OLD.observation_sha256
    AND NEW.created_at IS NOT DISTINCT FROM OLD.created_at THEN
