CREATE OR REPLACE FUNCTION preserve_projected_aircraft_catalog_row()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  is_projected BOOLEAN;
BEGIN
  IF TG_TABLE_NAME = 'aircraft_model_variants' THEN
    SELECT EXISTS (
      SELECT 1
      FROM aircraft_valuation_compatibility_projections projection
      WHERE projection.aircraft_model_variant_id = OLD.id
    ) INTO is_projected;
  ELSIF TG_TABLE_NAME = 'aircraft_models' THEN
    SELECT EXISTS (
      SELECT 1
      FROM aircraft_model_variants variant
      JOIN aircraft_valuation_compatibility_projections projection
        ON projection.aircraft_model_variant_id = variant.id
      WHERE variant.aircraft_model_id = OLD.id
    ) INTO is_projected;
  ELSE
    SELECT EXISTS (
      SELECT 1
      FROM aircraft_models model
      JOIN aircraft_model_variants variant
        ON variant.aircraft_model_id = model.id
      JOIN aircraft_valuation_compatibility_projections projection
        ON projection.aircraft_model_variant_id = variant.id
      WHERE model.aircraft_manufacturer_id = OLD.id
    ) INTO is_projected;
  END IF;
  IF is_projected THEN
    RAISE EXCEPTION 'projected aircraft compatibility catalog rows are immutable';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$function$;

