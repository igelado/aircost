CREATE OR REPLACE FUNCTION preserve_pending_aircraft_compatibility_catalog_row()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  protected_id BIGINT;
BEGIN
  IF TG_TABLE_NAME = 'aircraft_manufacturers' THEN
    SELECT aircraft_manufacturer_id INTO protected_id
    FROM aircraft_sale_listing_pending_compatibility_placeholder
    WHERE singleton_id = 1;
  ELSIF TG_TABLE_NAME = 'aircraft_models' THEN
    SELECT aircraft_model_id INTO protected_id
    FROM aircraft_sale_listing_pending_compatibility_placeholder
    WHERE singleton_id = 1;
  ELSE
    SELECT aircraft_model_variant_id INTO protected_id
    FROM aircraft_sale_listing_pending_compatibility_placeholder
    WHERE singleton_id = 1;
  END IF;
  IF OLD.id = protected_id THEN
    RAISE EXCEPTION 'pending aircraft compatibility catalog hierarchy is immutable';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$function$;

